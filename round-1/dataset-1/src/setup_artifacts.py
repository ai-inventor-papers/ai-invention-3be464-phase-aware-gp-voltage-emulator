import json
import os

# Create .aii directory if it doesn't exist
os.makedirs(".aii", exist_ok=True)

# Write manifest.yaml
with open(".aii/manifest.yaml", "w") as f:
    f.write("""entries:
  - path: full_data_out.json
    keep: Generated simulation data for experiments.
""")

# Create README.md
with open("README.md", "w") as f:
    f.write("""# Power Grid Phase Voltage Dataset

This dataset contains simulated phase voltages for the IEEE European LV asymmetric test feeder, generated using pandapower.

## Contents
- `full_data_out.json`: Simulated data containing inputs (load injections) and outputs (bus voltages).
- `data.py`: Script used to generate the dataset.

## How to run
1. Install dependencies: `pip install pandapower numpy pandas`
2. Run data generation script: `python3 data.py`

## Restoring removed files
This dataset is generated entirely from the `data.py` script. If `full_data_out.json` is deleted, it can be regenerated by running `python3 data.py`.
""")
